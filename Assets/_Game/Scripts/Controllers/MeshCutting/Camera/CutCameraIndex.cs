namespace OrganicEngineer.MeshCutting.CutCamera
{
    //==============================================================================
    // 기능: CutCameraIndex
    // 설명: 측면 카메라 인덱스를 다음/이전 방향으로 순환 계산한다.
    //==============================================================================
    // TODO: 비활성 슬롯 건너뛰기 옵션
    //
    //==============================================================================
    public class CutCameraIndex
    {
        //==============================================================================
        // 기능: CutCameraIndex::Next
        // 설명: 현재 인덱스에서 다음 측면 카메라 인덱스를 계산한다.
        //==============================================================================
        // TODO:
        //
        //==============================================================================
        public int Next(int currentIndex, int length)
        {
            // 다음 인덱스를 배열 길이로 순환시킴
            return (currentIndex + 1) % length;
        }

        //==============================================================================
        // 기능: CutCameraIndex::Previous
        // 설명: 현재 인덱스에서 이전 측면 카메라 인덱스를 계산한다.
        //==============================================================================
        // TODO:
        //
        //==============================================================================
        public int Previous(int currentIndex, int length)
        {
            // 음수 없이 이전 인덱스를 배열 길이로 순환시킴
            return (currentIndex + length - 1) % length;
        }
    }
}
